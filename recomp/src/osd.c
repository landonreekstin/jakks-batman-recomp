void osd_text(uint32_t *buf, int w, int h, int x, int y, int scale, const char *text)
{
    int len = 0;
    while (text[len]) len++;
    const int pad = scale * 2;
    const int bw = len * 6 * scale - scale + 2 * pad, bh = 7 * scale + 2 * pad;
    /* box: darken to a quarter */
    for (int yy = y; yy < y + bh && yy < h; yy++)
        for (int xx = x; xx < x + bw && xx < w; xx++)
            if (yy >= 0 && xx >= 0) buf[yy * w + xx] = (buf[yy * w + xx] >> 2) & 0x3f3f3f;
    for (int i = 0; i < len; i++) {
        const unsigned ch = (unsigned char)text[i];
        const uint8_t *g = FONT[ch >= 0x20 && ch < 0x7f ? ch - 0x20 : '?' - 0x20];
        for (int col = 0; col < 5; col++)
            for (int row = 0; row < 7; row++) {
                if (!(g[col] >> row & 1)) continue;
                const int px = x + pad + (i * 6 + col) * scale, py = y + pad + row * scale;
                for (int sy = 0; sy < scale; sy++)
                    for (int sx = 0; sx < scale; sx++) {
                        const int X = px + sx, Y = py + sy;
                        if (X >= 0 && X < w && Y >= 0 && Y < h) buf[Y * w + X] = 0xf0f0f0;
                    }
            }
    }
}
